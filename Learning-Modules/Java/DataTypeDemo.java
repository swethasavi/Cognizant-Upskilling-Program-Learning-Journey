public class DataTypeDemo {

    public static void main(String[] args) {

        int number = 10;
        float decimalNumber = 5.5f;
        double bigDecimal = 99.99;
        char letter = 'A';
        boolean isJavaEasy = true;

        System.out.println("Integer value: " + number);
        System.out.println("Float value: " + decimalNumber);
        System.out.println("Double value: " + bigDecimal);
        System.out.println("Char value: " + letter);
        System.out.println("Boolean value: " + isJavaEasy);
    }
}